"""Save and restore editable appearance through the shared Rust transaction."""
from noon import Blur, Glow, Pixels, Rectangle, Scene, VGroup


class EffectRestore(Scene):
    def construct(self):
        leaf = Rectangle(width=2, height=2, fill="#ffffff", fill_opacity=1, stroke=None).shift((-2, 0, 0))
        leaf.add_effect(Blur(radius=Pixels(1)), name="soften")
        leaf.add_effect(Glow(radius=Pixels(3.25), intensity=0.4, color="#ff0000"), name="halo")
        a = Rectangle(width=2, height=2, fill="#ffffff", fill_opacity=0.6, stroke=None).shift((1.5, 0, 0))
        b = Rectangle(width=2, height=2, fill="#ffffff", fill_opacity=0.6, stroke=None).shift((2.5, 0, 0))
        group = VGroup(a, b).set_object_opacity(0.6)
        group.add_effect(Blur(radius=Pixels(2)), name="soften", scope="composed")
        witness = Rectangle(width=0.4, height=0.4, fill="#ffffff", fill_opacity=1, stroke=None).shift((-4, -2, 0))
        self.add(leaf, group, witness)
        self.wait(0.5)
        leaf.save_state()
        group.save_state()
        leaf.set_effect("soften", radius=Pixels(3))
        leaf.set_effect("halo", intensity=1)
        group.set_effect("soften", radius=Pixels(4))
        group.set_object_opacity(0.25)
        self.wait(0.5)
        leaf.remove_effect("soften")
        leaf.remove_effect("halo")
        group.remove_effect("soften")
        self.wait(0.5)
        leaf.restore()
        group.restore()
        self.wait(0.5)
        leaf.saved_state.set_effect("halo", intensity=0)
        group.saved_state.set_object_opacity(0)
        self.wait(0.5)
        leaf.restore()
        group.restore()
        self.wait(0.5)
        leaf.remove_effect("soften")
        leaf.remove_effect("halo")
        group.remove_effect("soften")
        group.set_object_opacity(1)
        self.wait(0.5)
